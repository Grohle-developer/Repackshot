/** The two tables, derived from the paired source above. */
export const STRINGS: Readonly<Record<Lang, Readonly<Record<StringKey, string>>>> = {
  en: column(0),
  es: column(1),
};

export const LANGS: readonly Lang[] = ['en', 'es'];

let current: Lang = 'en';
const listeners = new Set<(lang: Lang) => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  for (const fn of listeners) fn(lang);
}

export function onLangChange(fn: (lang: Lang) => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export type Param = string | number | Label;

function resolve(p: Param, lang: Lang): string {
  if (typeof p === 'number') return formatNumber(p, lang);
  if (typeof p === 'string') return p;
  return p[lang];
}

function interpolate(template: string, params: Record<string, Param> | undefined, lang: Lang): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? resolve(params[name], lang) : m));
}

/** A string in the current language, with {params} filled in. */
export function t(key: StringKey, params?: Record<string, Param>): string {
  return interpolate(STRINGS[current][key], params, current);
}

/** A string in a given language. */
export function tIn(lang: Lang, key: StringKey, params?: Record<string, Param>): string {
  return interpolate(STRINGS[lang][key], params, lang);
}

/** The same string in both languages, e.g. for undo labels that survive a language switch. */
export function L(key: StringKey, params?: Record<string, Param>): Label {
  return { en: tIn('en', key, params), es: tIn('es', key, params) };
}

/** A catalogue Label in the current language. */
export function lbl(label: Label): string {
  return label[current];
}

/** Numbers with the separators of the language; at most `digits` decimals. */
export function formatNumber(n: number, lang: Lang = current, digits = 2): string {
  if (!Number.isFinite(n)) return '–';
  return new Intl.NumberFormat(lang === 'es' ? 'es-ES' : 'en-GB', { maximumFractionDigits: digits }).format(n);
}

/** "1 frame", "24 frames". */
export function framesText(n: number): string {
  return n === 1 ? t('queue.frame1') : t('queue.frames', { n: formatNumber(n, current, 0) });
}

/** Seconds as M:SS (or H:MM:SS). */
/** A SIMD path of the native engine as the status bar shows it (`avx2` -> `AVX2`, scalar translated). */
export function isaLabel(isa: string | undefined): string {
  return !isa || isa === 'scalar' ? t('status.isaScalar') : isa.toUpperCase();
}

export function formatClock(seconds: number): string {
  const s = Math.max(0, Math.round(seconds));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const ss = String(s % 60).padStart(2, '0');
  return h > 0 ? `${h}:${String(m).padStart(2, '0')}:${ss}` : `${m}:${ss}`;
}
