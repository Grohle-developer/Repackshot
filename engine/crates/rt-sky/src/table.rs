//! The fitted table as the engine's and the preview's data: `f32` values, their SHA-256, and the
//! generated sources (`rt-core/src/sky_table.rs`, `src/core/sky-table.ts`).
//!
//! Layout, flattened in this order: `COEFFICIENTS[turbidity 1..10][albedo 0, 1][R, G, B]
//! [control point 0..5][A..I]` and `RADIANCE[turbidity][albedo][channel][control point]`. The
//! hash is of the little-endian bytes of every `f32` of `COEFFICIENTS` and then of `RADIANCE`.

use crate::dataset::Recipe;
use crate::model::{Knot, Table, ALBEDOS, CHANNELS, CONTROL, PARAMS, TURBIDITIES};
use crate::sha256;
use std::fmt::Write as _;

/// Number of coefficients in the table.
pub const COEFFICIENT_COUNT: usize = TURBIDITIES * ALBEDOS * CHANNELS * CONTROL * PARAMS;
/// Number of radiance control points in the table.
pub const RADIANCE_COUNT: usize = TURBIDITIES * ALBEDOS * CHANNELS * CONTROL;

/// The table rounded to `f32`, flattened.
#[derive(Clone, Debug, PartialEq)]
pub struct Flat {
    /// See the module documentation.
    pub coefficients: Vec<f32>,
    /// See the module documentation.
    pub radiance: Vec<f32>,
}

impl Flat {
    /// `table` in `f32`.
    pub fn new(table: &Table) -> Flat {
        let mut coefficients = Vec::with_capacity(COEFFICIENT_COUNT);
        let mut radiance = Vec::with_capacity(RADIANCE_COUNT);
        for knot in &table.knots {
            for row in &knot.coefficients {
                coefficients.extend(row.iter().map(|&v| v as f32));
            }
            radiance.extend(knot.radiance.iter().map(|&v| v as f32));
        }
        Flat {
            coefficients,
            radiance,
        }
    }

    /// The table these values are (in `f64`).
    pub fn table(&self) -> Table {
        let knots = (0..TURBIDITIES * ALBEDOS * CHANNELS)
            .map(|i| {
                let mut coefficients = [[0.0; PARAMS]; CONTROL];
                for (k, row) in coefficients.iter_mut().enumerate() {
                    for (j, v) in row.iter_mut().enumerate() {
                        *v = self.coefficients[(i * CONTROL + k) * PARAMS + j] as f64;
                    }
                }
                let mut radiance = [0.0; CONTROL];
                for (k, v) in radiance.iter_mut().enumerate() {
                    *v = self.radiance[i * CONTROL + k] as f64;
                }
                Knot {
                    coefficients,
                    radiance,
                }
            })
            .collect();
        Table { knots }
    }

    /// SHA-256 of the values, in lower-case hexadecimal.
    pub fn sha256(&self) -> String {
        let bytes: Vec<u8> = self
            .coefficients
            .iter()
            .chain(&self.radiance)
            .flat_map(|v| v.to_le_bytes())
            .collect();
        sha256::hex(&sha256::digest(&bytes))
    }
}

/// An `f32` as the shortest literal that reads back as the same value.
pub fn literal(v: f32) -> String {
    let s = format!("{v:?}");
    if s.contains('.') || s.contains('e') {
        s
    } else {
        format!("{s}.0")
    }
}

/// Values as lines of `per` literals, each line indented by `indent`.
fn lines(values: &[f32], per: usize, indent: &str) -> String {
    let mut s = String::new();
    for chunk in values.chunks(per) {
        s.push_str(indent);
        let parts: Vec<String> = chunk.iter().map(|&v| literal(v)).collect();
        s.push_str(&parts.join(", "));
        s.push_str(",\n");
    }
    s
}

/// The recipe in one sentence.
pub fn recipe_text(recipe: &Recipe) -> String {
    format!(
        "seed {:#x}, {} multiple-scattering paths per direction, {} Sun elevations (90° (i / {})³), \
         the 768 directions of `rt_sky::dataset::Grid::fit`, 34 bands from 380 to 720 nm",
        recipe.seed,
        recipe.paths,
        recipe.elevations,
        recipe.elevations - 1
    )
}

/// `rt-core/src/sky_table.rs`.
pub fn rust_source(flat: &Flat, recipe: &Recipe) -> String {
    let hash = flat.sha256();
    let mut s = String::new();
    let _ = write!(
        s,
        "//! The coefficients of the physical sky (phase E5c), generated by `rt-sky table` from our own\n\
         //! atmosphere simulation and fit (`engine/crates/rt-sky`): do not edit by hand.\n\
         //!\n\
         //! Recipe: {}.\n\
         //! Regenerate with `cargo run --release -p rt-sky -- table` from `engine/`; the same\n\
         //! recipe gives the same numbers on any machine and with any number of threads.\n\
         //!\n\
         //! SHA-256 of the values (little-endian `f32`, [`COEFFICIENTS`] then [`RADIANCE`]):\n\
         //! `{hash}`.\n\
         //! `src/core/sky-table.ts` holds the same values for the preview.\n\
         \n\
         /// SHA-256 of [`COEFFICIENTS`] then [`RADIANCE`] as little-endian `f32`.\n\
         pub const SHA256: &str = \"{hash}\";\n\
         \n\
         /// The coefficients `A` to `I` of the distribution, flattened\n\
         /// `[turbidity 1..10][albedo 0, 1][R, G, B][Bézier control point 0..5][A..I]`.\n\
         #[rustfmt::skip]\n\
         #[allow(clippy::approx_constant)]\n\
         pub const COEFFICIENTS: [f32; {}] = [\n",
        wrap_doc(&recipe_text(recipe)),
        COEFFICIENT_COUNT
    );
    s.push_str(&lines(&flat.coefficients, PARAMS, "    "));
    let _ = write!(
        s,
        "];\n\
         \n\
         /// The radiance scale `L_M`, flattened `[turbidity][albedo][channel][control point]`.\n\
         #[rustfmt::skip]\n\
         #[allow(clippy::approx_constant)]\n\
         pub const RADIANCE: [f32; {}] = [\n",
        RADIANCE_COUNT
    );
    s.push_str(&lines(&flat.radiance, CONTROL, "    "));
    s.push_str("];\n");
    s
}

/// A long sentence for a `//!` line: wrapped at about 96 columns.
fn wrap_doc(text: &str) -> String {
    let mut out = String::new();
    let mut line = String::new();
    for word in text.split(' ') {
        if line.len() + word.len() + 1 > 86 && !line.is_empty() {
            out.push_str(&line);
            out.push_str("\n//! ");
            line.clear();
        }
        if !line.is_empty() {
            line.push(' ');
        }
        line.push_str(word);
    }
    out.push_str(&line);
    out
}

/// `src/core/sky-table.ts`.
pub fn ts_source(flat: &Flat) -> String {
    let hash = flat.sha256();
    let mut s = String::new();
    let _ = write!(
        s,
        "// The coefficients of the physical sky (phase E5c), generated by `rt-sky table` (engine/crates/rt-sky) from\n\
         // our own atmosphere simulation and fit: do not edit by hand. The same f32 values as the engine's\n\
         // (engine/crates/rt-core/src/sky_table.rs, SHA-256 of the little-endian f32s, coefficients then radiance:\n\
         // {hash}); a test of rt-sky checks that this file is what its generator writes for that table.\n\
         \n\
         export const SKY_TABLE_SHA256 = '{hash}';\n\
         \n\
         /** Coefficients A to I, flattened [turbidity 1..10][albedo 0, 1][R, G, B][Bézier control point 0..5][A..I]. */\n\
         export const SKY_COEFFICIENTS = new Float32Array([\n"
    );
    s.push_str(&lines(&flat.coefficients, PARAMS, "  "));
    s.push_str(
        "]);\n\
         \n\
         /** The radiance scale L_M, flattened [turbidity][albedo][channel][control point]. */\n\
         export const SKY_RADIANCE = new Float32Array([\n",
    );
    s.push_str(&lines(&flat.radiance, CONTROL, "  "));
    s.push_str("]);\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dataset::RECIPE;

    fn committed() -> Flat {
        Flat {
            coefficients: rt_core::sky_table::COEFFICIENTS.to_vec(),
            radiance: rt_core::sky_table::RADIANCE.to_vec(),
        }
    }

    #[test]
    fn the_committed_table_matches_its_hash_and_its_generated_sources() {
        let flat = committed();
        assert_eq!(flat.sha256(), rt_core::sky_table::SHA256);
        assert!(flat
            .coefficients
            .iter()
            .chain(&flat.radiance)
            .all(|v| v.is_finite()));
        // The engine's file and the preview's are exactly what the generator writes for these
        // values: neither can drift from the other or from its recorded recipe and hash.
        let rust = include_str!("../../rt-core/src/sky_table.rs");
        assert!(
            rust == rust_source(&flat, &RECIPE),
            "sky_table.rs is stale: run `rt-sky table`"
        );
        let ts = include_str!("../../../../src/core/sky-table.ts");
        assert!(
            ts == ts_source(&flat),
            "src/core/sky-table.ts is stale: run `rt-sky table`"
        );
        // f32 → f64 → f32 is the identity.
        assert_eq!(Flat::new(&flat.table()), flat);
    }

    #[test]
    fn literals_read_back_exactly() {
        for v in [
            0.1f32,
            -1.5e-7,
            1.0,
            0.0,
            -0.0,
            123_456.79,
            f32::MIN_POSITIVE,
        ] {
            let s = literal(v);
            assert_eq!(s.parse::<f32>().unwrap().to_bits(), v.to_bits(), "{s}");
            assert!(s.contains('.') || s.contains('e'));
        }
    }
}
